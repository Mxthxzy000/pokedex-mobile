-- Cria a tabela de pokémons
create table if not exists public.pokemon (
  id bigint generated by default as identity primary key,
  nome text not null,
  tipo text not null,
  localizacao text not null default '',
  data_registro timestamptz not null default now(),
  foto text not null default '',
  hp integer not null default 0 check (hp >= 0),
  ataque integer not null default 0 check (ataque >= 0),
  defesa integer not null default 0 check (defesa >= 0),
  observacoes text not null default ''
);

-- Habilita Row Level Security
alter table public.pokemon enable row level security;

-- Permite leitura pública
create policy "Permitir leitura pública" on public.pokemon
  for select using (true);

-- Permite inserção pública
create policy "Permitir inserção pública" on public.pokemon
  for insert with check (true);